"""Python reference implementation of the KAVACH LSB scan.

The web scanner (web/src/scan.ts) must produce exactly the findings this
module produces. It loads files with torch.load(weights_only=False), so it is
only ever run on samples generated by make_samples.py, never on untrusted files.
"""
import json
import sys

import numpy as np
import torch

SIGNATURES = [b"EICAR-STANDARD-ANTIVIRUS-TEST-FILE"]
WINDOW_BYTES = 64
STRIDE_BYTES = 8
THRESHOLD = 0.75

INT_VIEW = {
    torch.float32: torch.int32,
    torch.float16: torch.int16,
    torch.bfloat16: torch.int16,
    torch.float64: torch.int64,
}


def lsb_bits(t: torch.Tensor) -> np.ndarray:
    as_int = t.detach().contiguous().view(INT_VIEW[t.dtype]).flatten()
    return (as_int & 1).to(torch.uint8).numpy()


def scan_bits(bits: np.ndarray):
    findings = []
    peak = 0.0
    for phase in range(8):
        usable = (bits.size - phase) // 8
        if usable < WINDOW_BYTES:
            continue
        data = np.packbits(bits[phase:phase + usable * 8])
        printable = (data >= 32) & (data <= 126)
        cumsum = np.concatenate(([0], np.cumsum(printable, dtype=np.int64)))
        starts = np.arange(0, usable - WINDOW_BYTES + 1, STRIDE_BYTES)
        ratios = (cumsum[starts + WINDOW_BYTES] - cumsum[starts]) / WINDOW_BYTES
        peak = max(peak, float(ratios.max()))
        hit_starts = starts[ratios >= THRESHOLD]
        hit_ratios = ratios[ratios >= THRESHOLD]
        regions = []
        for s, r in zip(hit_starts, hit_ratios):
            if regions and s <= regions[-1][1]:
                regions[-1][1] = max(regions[-1][1], s + WINDOW_BYTES)
                regions[-1][2] = max(regions[-1][2], r)
            else:
                regions.append([int(s), int(s + WINDOW_BYTES), float(r)])
        for s, e, r in regions:
            decoded = data[s:e].tobytes()
            sig = next((x for x in SIGNATURES if x in decoded), None)
            findings.append({
                "bit_start": int(phase + s * 8),
                "bit_end": int(phase + e * 8),
                "bit_phase": phase,
                "printable_ratio": r,
                "severity": "CRITICAL" if sig else "SUSPICIOUS",
                "matched_signature": sig.decode() if sig else None,
                "decoded_hex": decoded.hex(),
            })
    return findings, peak


def flatten(obj, prefix=""):
    """Named tensors using the same naming rule as web/src/torchzip.ts."""
    if isinstance(obj, torch.nn.Module):
        for k, v in obj.state_dict(keep_vars=True).items():
            yield prefix + k, v
    elif isinstance(obj, torch.Tensor):
        yield prefix.rstrip("."), obj
    elif isinstance(obj, dict):
        for k, v in obj.items():
            yield from flatten(v, f"{prefix}{k}.")
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            yield from flatten(v, f"{prefix}{i}.")


def load_named(path):
    if path.endswith(".safetensors"):
        from safetensors.torch import load_file
        return list(load_file(path).items())
    return list(flatten(torch.load(path, map_location="cpu", weights_only=False)))


def scan_named(named):
    findings, peaks, skipped = [], {}, []
    for name, t in named:
        if t.dtype not in INT_VIEW:
            skipped.append(name)
            continue
        f, peak = scan_bits(lsb_bits(t))
        peaks[name] = peak
        for x in f:
            findings.append({"layer": name, **x})
    return {"findings": findings, "peaks": peaks, "skipped": skipped}


if __name__ == "__main__":
    print(json.dumps(scan_named(load_named(sys.argv[1])), indent=1))
